require __DIR__ . '/../app/plugins/synapse_core/lib/synapse_platform.php';

$topics = ['php' => 'PHP 8.1 or newer', 'ext' => 'Missing PHP extension (example: intl)', 'perms' => 'Folder not writable (example: db/)',
    'https' => 'HTTPS', 'protect' => 'db/ downloadable from the web (.htaccess ignored)', 'mail' => 'Finding the mail server'];
$paths = ['cpanel' => '/home*/<user>/public_html/...', 'plesk' => '/var/www/vhosts/<domain>/...', 'directadmin' => '/home/<user>/domains/<domain>/public_html/...',
    'hestia' => '/home/<user>/web/<domain>/public_html/...', 'cloudpanel' => '/home/<user>/htdocs/<domain>/...', 'aapanel' => '/www/wwwroot/<site>/...',
    'ispconfig' => '/var/www/clients/client<N>/web<N>/...', 'plain' => 'anything else'];

$o = "# SynapseMail on hosting panels\n\nCopyright (c) 2026 SynapseCyber.io · Developed by Milad Ahmadipour · CC BY-NC-ND 4.0\n\n"
    . "Generated by `tools/panel-docs.php` from the installer's help text. The web installer detects the hosting panel from the\n"
    . "install path and shows these steps next to each failed check (\"How to fix on <panel>\"). If the detection is wrong,\n"
    . "choose your panel at the top of the Environment step.\n\n## How the panel is detected\n\n| Panel | Install path |\n|---|---|\n";
foreach (synapse_platform::PANELS as $id => $name) {
    $o .= "| $name | `{$paths[$id]}` |\n";
}
$o .= "\nThe web server (Apache, LiteSpeed, nginx) is read from the server signature, but the deciding test is the protection\n"
    . "probe: the installer writes a file to `db/` and tries to download it. If that works, `.htaccess` is ignored and the\n"
    . "install stays blocked until the folders are protected. See [TROUBLESHOOTING.md](TROUBLESHOOTING.md#nginx).\n";
foreach (synapse_platform::PANELS as $id => $name) {
    $o .= "\n## $name\n\n";
    foreach ($topics as $k => $title) {
        $o .= "- **$title:** " . synapse_platform::help($k, $id, ['ext' => 'intl', 'perms' => 'db/'][$k] ?? '') . "\n";
    }
}
file_put_contents(__DIR__ . '/../docs/HOSTING-PANELS.md', $o);
echo "docs/HOSTING-PANELS.md written\n";
